// Install from Chrome on Android.
import { record } from "./stage.mjs"
import { android } from "./install-scenes.mjs"

function build(B) {
  B.hidden("#scrim", "#menu", "#dialog", "#toast", "#standalone", "#kt")
  B.cam(0.72, 240, 380, 0)
  B.say("Open Chrome's menu", 1)

  B.wait(450)
  B.cam(1.4, 300, 140, 1200)
  B.wait(650)
  B.ring("#menu-btn")
  B.tap("#menu-btn", { glide: 800 })
  B.unring()
  B.show("#scrim", {}, 320, "std")
  B.show("#menu", { s: 0.86 }, 480)

  B.wait(550)
  B.say("Tap Install app", 2)
  B.cam(1.4, 280, 250, 900)
  B.wait(350)
  B.ring("#install")
  B.wait(200)
  B.tap("#install", { glide: 650 })
  B.unring()
  B.hide("#menu", { s: 0.96 }, 240)
  B.wait(160)
  B.show("#dialog", { s: 0.92 }, 500)
  B.cam(1.3, 240, 330, 900)

  B.wait(550)
  B.say("Tap Install", 3)
  B.wait(200)
  B.ring("#confirm")
  B.wait(250)
  B.tap("#confirm", { glide: 600 })
  B.unring()
  B.lift()
  B.hide("#dialog", { s: 0.96 }, 260)
  B.wait(140)
  B.hide("#scrim", {}, 380, "std")
  B.hide("#browser", { s: 0.94 }, 480)
  B.cam(0.95, 240, 330, 1000)

  B.wait(650)
  B.say("Open it from your Home screen", 4)
  B.show("#kt", { s: 0.4 }, 650, "pop")
  B.show("#toast", { y: 16 }, 460, "out", 220)
  B.wait(950)
  const k = B.box("#kt img")
  B.cam(1.4, k.left + k.width / 2, k.top + k.height / 2 + 40, 900)
  B.wait(350)
  B.hide("#toast", { y: 8 }, 300)
  B.ring("#kt img")
  B.wait(200)
  B.tap("#kt img", { glide: 700 })
  B.unring()
  B.lift()

  // The app grows out of its icon.
  const L = B.box("#standalone"), I = B.box("#kt img")
  B.set("#standalone", { x: I.left - L.left, y: I.top - L.top, s: I.width / L.width })
  B.to("#standalone", { x: 0, y: 0, s: 1 }, 650, "out")
  B.to("#standalone", { o: 1, b: 0 }, 240, "std")
  B.to("#home", { s: 1.08 }, 650, "out")
  B.wait(250)
  B.say("It opens full screen, like an app")
  B.cam(0.72, 240, 380, 1300)
  B.wait(2300)
  return B.loop(1100)
}

export default (out) => record(out, { scene: android(), appH: 760, pointer: "finger", build, posterAt: 0.4 })

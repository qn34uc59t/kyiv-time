// Add to Home Screen from Safari on iPhone.
import { record } from "./stage.mjs"
import { ios } from "./install-scenes.mjs"

function build(B) {
  B.hidden("#scrim", "#sharesheet", "#addsheet", "#standalone", "#kt")
  B.cam(0.72, 240, 380, 0)
  B.say("In Safari, tap Share", 1)

  B.wait(450)
  B.cam(1.4, 240, 690, 1200)
  B.wait(650)
  B.ring("#share")
  B.tap("#share", { glide: 800, from: [330, 560] })
  B.unring()
  B.show("#scrim", {}, 320, "std")
  B.show("#sharesheet", { y: 320 }, 620)
  B.cam(1.25, 240, 560, 1000)

  B.wait(750)
  B.say("Tap Add to Home Screen", 2)
  B.wait(250)
  B.ring("#addhome")
  B.wait(200)
  B.tap("#addhome", { glide: 650 })
  B.unring()
  B.hide("#sharesheet", { y: 320 }, 340)
  B.wait(120)
  B.show("#addsheet", { y: 700 }, 680)
  B.cam(1.35, 240, 140, 1100)

  B.wait(850)
  B.say("Tap Add", 3)
  B.wait(200)
  B.ring("#add")
  B.wait(250)
  B.tap("#add", { glide: 650 })
  B.unring()
  B.lift()
  B.hide("#addsheet", { y: 700 }, 460)
  B.wait(160)
  B.hide("#scrim", {}, 380, "std")
  B.hide("#browser", { s: 0.94 }, 480)
  B.cam(0.95, 240, 330, 1000)

  B.wait(650)
  B.say("Open it from your Home Screen", 4)
  B.show("#kt", { s: 0.4 }, 650, "pop")
  B.wait(950)
  const k = B.box("#kt img")
  B.cam(1.4, k.left + k.width / 2, k.top + k.height / 2 + 40, 900)
  B.wait(550)
  B.ring("#kt img")
  B.wait(200)
  B.tap("#kt img", { glide: 700 })
  B.unring()
  B.lift()

  // The app grows out of its icon.
  const L = B.box("#standalone"), I = B.box("#kt img")
  B.set("#standalone", { x: I.left - L.left, y: I.top - L.top, s: I.width / L.width })
  B.to("#standalone", { x: 0, y: 0, s: 1 }, 650, "out")
  B.to("#standalone", { o: 1, b: 0 }, 240, "std")
  B.to("#home", { s: 1.08 }, 650, "out")
  B.wait(250)
  B.say("It opens full screen, like an app")
  B.cam(0.72, 240, 380, 1300)
  B.wait(2300)
  return B.loop(1100)
}

export default (out) => record(out, { scene: ios(), appH: 760, pointer: "finger", build, posterAt: 0.3 })
